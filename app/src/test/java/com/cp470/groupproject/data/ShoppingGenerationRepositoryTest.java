package com.cp470.groupproject.data;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;

import android.content.Context;

import androidx.arch.core.executor.testing.InstantTaskExecutorRule;
import androidx.room.Room;
import androidx.test.core.app.ApplicationProvider;
import androidx.test.ext.junit.runners.AndroidJUnit4;

import com.cp470.groupproject.data.db.PantryDatabase;
import com.cp470.groupproject.data.entity.ShoppingItem;
import com.cp470.groupproject.data.repository.PantryRepository;

import org.junit.After;
import org.junit.Before;
import org.junit.Rule;
import org.junit.Test;
import org.junit.runner.RunWith;
import org.robolectric.annotation.Config;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.List;

/** Tests replacing the auto-generated shopping items with an in-memory database. */
@RunWith(AndroidJUnit4.class)
@Config(sdk = 34)
public class ShoppingGenerationRepositoryTest {

    @Rule
    public InstantTaskExecutorRule instantTaskExecutorRule = new InstantTaskExecutorRule();

    private PantryDatabase db;
    private PantryRepository repository;

    @Before
    public void setUp() {
        Context context = ApplicationProvider.getApplicationContext();
        db = Room.inMemoryDatabaseBuilder(context, PantryDatabase.class)
                .allowMainThreadQueries().build();
        repository = new PantryRepository(db, Runnable::run);
    }

    @After
    public void tearDown() {
        db.close();
    }

    private List<ShoppingItem> currentList() {
        return LiveDataTestUtil.getValue(repository.getShoppingItems());
    }

    private static ShoppingItem auto(String name) {
        ShoppingItem item = new ShoppingItem(name, 1, "", null);
        item.autoGenerated = true;
        return item;
    }

    private static boolean hasName(List<ShoppingItem> items, String name) {
        for (ShoppingItem item : items) {
            if (item.name.equals(name)) return true;
        }
        return false;
    }

    @Test
    public void replaceAuto_keepsManualAndCheckedItems() {
        repository.addShoppingItem(new ShoppingItem("Manual", 1, "", null), null);
        ShoppingItem ticked = auto("Ticked");
        ticked.checked = true;
        repository.addShoppingItem(ticked, null);

        repository.replaceAutoGeneratedShoppingItems(new ArrayList<>(), null);

        List<ShoppingItem> list = currentList();
        assertEquals(2, list.size());
        assertTrue(hasName(list, "Manual"));
        assertTrue(hasName(list, "Ticked"));
    }

    @Test
    public void replaceAuto_removesPreviousPendingAuto() {
        repository.addShoppingItem(auto("Old"), null);

        repository.replaceAutoGeneratedShoppingItems(
                new ArrayList<>(Arrays.asList(auto("New"))), null);

        List<ShoppingItem> list = currentList();
        assertEquals(1, list.size());
        assertEquals("New", list.get(0).name);
    }

    @Test
    public void replaceAuto_isIdempotent() {
        repository.replaceAutoGeneratedShoppingItems(
                new ArrayList<>(Arrays.asList(auto("Eggs"), auto("Sugar"))), null);
        repository.replaceAutoGeneratedShoppingItems(
                new ArrayList<>(Arrays.asList(auto("Eggs"), auto("Sugar"))), null);

        assertEquals(2, currentList().size());
    }

    @Test
    public void replaceAuto_normalizesNames() {
        repository.replaceAutoGeneratedShoppingItems(
                new ArrayList<>(Arrays.asList(auto("2% Milk 1L"))), null);

        assertEquals("milk", currentList().get(0).normalizedName);
    }

    @Test
    public void replaceAuto_reportsHowManyWereInserted() {
        final int[] count = {-1};

        repository.replaceAutoGeneratedShoppingItems(
                new ArrayList<>(Arrays.asList(auto("A"), auto("B"), auto("C"))),
                inserted -> count[0] = inserted);

        assertEquals(3, count[0]);
    }
}
