package com.cp470.groupproject.shopping;

import static org.junit.Assert.assertEquals;
import static org.junit.Assert.assertTrue;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.verify;
import static org.mockito.Mockito.when;

import com.cp470.groupproject.data.entity.MealPlan;
import com.cp470.groupproject.data.entity.ShoppingItem;
import com.cp470.groupproject.data.model.MealType;
import com.cp470.groupproject.data.model.StockSummary;
import com.cp470.groupproject.data.repository.PantryRepository;

import org.junit.Test;
import org.junit.runner.RunWith;
import org.mockito.ArgumentCaptor;
import org.mockito.Captor;
import org.mockito.Mock;
import org.mockito.junit.MockitoJUnitRunner;

import java.util.ArrayList;
import java.util.Arrays;
import java.util.Collections;
import java.util.List;

/**
 * Tests that the generator reads plans, stock and list and saves the right result. the
 * repository is a mockito mock, so no database is involved.
 */
@RunWith(MockitoJUnitRunner.class)
public class ShoppingListGeneratorTest {

    private static final long FROM = 1_000L;
    private static final long TO = 2_000L;

    @Mock
    PantryRepository repo;

    @Captor
    ArgumentCaptor<List<ShoppingItem>> captor;

    @Captor
    ArgumentCaptor<PantryRepository.ResultCallback<Integer>> callbackCaptor;

    private static MealPlan plan(String... ingredients) {
        return new MealPlan(FROM, MealType.DINNER, "id", "Omelette",
                new ArrayList<>(Arrays.asList(ingredients)));
    }

    private static StockSummary stock(String name, String unit, double quantity) {
        StockSummary row = new StockSummary();
        row.normalizedName = name;
        row.unit = unit;
        row.totalQuantity = quantity;
        return row;
    }

    private void givenPlans(MealPlan... plans) {
        when(repo.getMealPlansSync(FROM, TO)).thenReturn(Arrays.asList(plans));
        when(repo.getStockSummarySync()).thenReturn(Collections.emptyList());
        when(repo.getShoppingItemsSync()).thenReturn(Collections.emptyList());
    }

    /** runs a generation, lets the repository finish with {@code added} items, returns the result */
    private ShoppingListGenerator.Result generateAndFinish(int added) {
        List<ShoppingListGenerator.Result> results = new ArrayList<>();
        new ShoppingListGenerator(repo).generate(FROM, TO, results::add);
        verify(repo).replaceAutoGeneratedShoppingItems(any(), callbackCaptor.capture());
        callbackCaptor.getValue().onResult(added);
        assertEquals(1, results.size());
        return results.get(0);
    }

    @Test
    public void generate_readsPlanStockAndList_thenReplacesAutoItems() {
        when(repo.getMealPlansSync(FROM, TO))
                .thenReturn(Collections.singletonList(plan("2 eggs", "milk")));
        when(repo.getStockSummarySync())
                .thenReturn(Collections.singletonList(stock("milk", "L", 1.0)));
        when(repo.getShoppingItemsSync()).thenReturn(Collections.emptyList());

        new ShoppingListGenerator(repo).generate(FROM, TO, null);

        verify(repo).replaceAutoGeneratedShoppingItems(captor.capture(), any());
        assertEquals(1, captor.getValue().size());
        assertEquals("Eggs", captor.getValue().get(0).name);
        assertEquals(2.0, captor.getValue().get(0).quantity, 1e-9);
    }

    @Test
    public void generate_nothingMissing_stillReplacesWithEmptyList() {
        givenPlans();

        new ShoppingListGenerator(repo).generate(FROM, TO, null);

        // an empty list still clears the old auto-generated items
        verify(repo).replaceAutoGeneratedShoppingItems(captor.capture(), any());
        assertTrue(captor.getValue().isEmpty());
    }

    @Test
    public void generate_callbackGetsTheNumberOfItemsAdded() {
        givenPlans(plan("2 eggs"));

        assertEquals(1, generateAndFinish(1).added);
    }

    @Test
    public void generate_callbackGetsTheNumberOfPendingMeals() {
        givenPlans(plan("2 eggs"), plan("rice"));

        assertEquals(2, generateAndFinish(2).meals);
    }

    @Test
    public void generate_noMealsInThePeriod_reportsZeroMeals() {
        givenPlans();

        assertEquals(0, generateAndFinish(0).meals);
    }

    @Test
    public void generate_onlyCookedMeals_reportsZeroMeals() {
        MealPlan cooked = plan("2 eggs");
        cooked.completed = true;
        givenPlans(cooked);

        assertEquals(0, generateAndFinish(0).meals);
    }

    @Test
    public void generate_mealsButNothingMissing_reportsMealsWithZeroAdded() {
        when(repo.getMealPlansSync(FROM, TO))
                .thenReturn(Collections.singletonList(plan("milk")));
        when(repo.getStockSummarySync())
                .thenReturn(Collections.singletonList(stock("milk", "L", 1.0)));
        when(repo.getShoppingItemsSync()).thenReturn(Collections.emptyList());

        ShoppingListGenerator.Result result = generateAndFinish(0);

        assertEquals(1, result.meals);
        assertEquals(0, result.added);
    }
}
