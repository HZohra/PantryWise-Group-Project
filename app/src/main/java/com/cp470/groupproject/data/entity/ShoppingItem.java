package com.cp470.groupproject.data.entity;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.room.Entity;
import androidx.room.Ignore;
import androidx.room.Index;
import androidx.room.PrimaryKey;

/** One line of the shopping list. */

@Entity(tableName = "shopping_items", indices = {@Index("normalizedName")})
public class ShoppingItem {
    @PrimaryKey(autoGenerate = true)
    public long id;

    @NonNull
    public String name = "";

    /** canonical name, same normalization as FoodItem, so stock and list can be compared */
    @NonNull
    public String normalizedName = "";

    /** quantity required */
    public double quantity = 1;

    @NonNull
    public String unit = "";

    /** target store, null when the user did not choose one */
    @Nullable
    public String store;

    /** true once the user ticked the item in the store */
    public boolean checked;

    /** true when created by the automatic list generator instead of by the user */
    public boolean autoGenerated;

    /** creation time in milliseconds */
    public long createdAt;

    /** empty constructor required by room */
    public ShoppingItem() { }

    @Ignore
    public ShoppingItem(@NonNull String name, double quantity, @NonNull String unit,
                        @Nullable String store) {
        this.name = name;
        this.quantity = quantity;
        this.unit = unit;
        this.store = store;
        this.createdAt = System.currentTimeMillis();
    }
}