package com.cp470.groupproject.ui.shoppinglist;

import android.content.Context;
import android.graphics.Paint;
import android.view.LayoutInflater;
import android.view.View;
import android.view.ViewGroup;
import android.widget.CheckBox;
import android.widget.TextView;

import androidx.annotation.NonNull;
import androidx.recyclerview.widget.DiffUtil;
import androidx.recyclerview.widget.ListAdapter;
import androidx.recyclerview.widget.RecyclerView;

import com.cp470.groupproject.R;
import com.cp470.groupproject.data.entity.ShoppingItem;
import com.cp470.groupproject.util.ShoppingListFormatter;
import com.cp470.groupproject.util.StoreGrouper.ShoppingRow;
import com.cp470.groupproject.util.StoreGrouper.StoreGroup;

import java.util.Objects;

/**
 * Adapter of the shopping list. it has two kinds of row: a header with the name of a shop (and a
 * maps button) and one row per item with a checkbox, name and details.
 */
public class ShoppingListAdapter extends ListAdapter<ShoppingRow, RecyclerView.ViewHolder> {

    /** view type of a shop header */
    public static final int TYPE_HEADER = 0;
    /** view type of an item */
    public static final int TYPE_ITEM = 1;

    /** events of the rows, handled by the activity */
    public interface Listener {
        /** the checkbox of a row was ticked or unticked by the user */
        void onCheckedChanged(ShoppingItem item, boolean checked);

        /** a row was tapped (to edit it) */
        void onItemClicked(ShoppingItem item);

        /** the maps button of a shop header was tapped */
        void onMapClicked(StoreGroup group);
    }

    private static final DiffUtil.ItemCallback<ShoppingRow> DIFF =
            new DiffUtil.ItemCallback<ShoppingRow>() {
                @Override
                public boolean areItemsTheSame(@NonNull ShoppingRow a, @NonNull ShoppingRow b) {
                    if (a.isHeader() != b.isHeader()) {
                        return false;
                    }
                    return a.isHeader() ? a.group.key.equals(b.group.key)
                            : a.item.id == b.item.id;
                }

                // ShoppingItem has no equals(), so compare the shown fields one by one
                @Override
                public boolean areContentsTheSame(@NonNull ShoppingRow a, @NonNull ShoppingRow b) {
                    if (a.isHeader()) {
                        return Objects.equals(a.group.name, b.group.name)
                                && Objects.equals(a.group.type, b.group.type)
                                && a.group.items.size() == b.group.items.size();
                    }
                    ShoppingItem x = a.item;
                    ShoppingItem y = b.item;
                    return x.name.equals(y.name)
                            && x.quantity == y.quantity
                            && x.unit.equals(y.unit)
                            && Objects.equals(x.store, y.store)
                            && x.checked == y.checked
                            && x.autoGenerated == y.autoGenerated;
                }
            };

    private final Listener listener;

    /** @param listener receives the clicks of the rows */
    public ShoppingListAdapter(@NonNull Listener listener) {
        super(DIFF);
        this.listener = listener;
    }

    @Override
    public int getItemViewType(int position) {
        return getItem(position).isHeader() ? TYPE_HEADER : TYPE_ITEM;
    }

    @NonNull
    @Override
    public RecyclerView.ViewHolder onCreateViewHolder(@NonNull ViewGroup parent, int viewType) {
        LayoutInflater inflater = LayoutInflater.from(parent.getContext());
        if (viewType == TYPE_HEADER) {
            return new HeaderHolder(inflater.inflate(R.layout.item_store_header, parent, false));
        }
        return new ItemHolder(inflater.inflate(R.layout.item_shopping, parent, false));
    }

    @Override
    public void onBindViewHolder(@NonNull RecyclerView.ViewHolder holder, int position) {
        ShoppingRow row = getItem(position);
        if (row.isHeader()) {
            bindHeader((HeaderHolder) holder, row.group);
        } else {
            bindItem((ItemHolder) holder, row.item);
        }
    }

    private void bindHeader(HeaderHolder holder, StoreGroup group) {
        Context context = holder.itemView.getContext();
        String title = group.name != null ? group.name
                : context.getString(StoreLabels.nameRes(group.type));
        int count = group.items.size();
        holder.name.setText(title);
        holder.count.setText(context.getResources()
                .getQuantityString(R.plurals.shopping_group_count, count, count));
        holder.map.setContentDescription(context.getString(R.string.shopping_map_open, title));
        holder.map.setOnClickListener(v -> listener.onMapClicked(group));
    }

    private void bindItem(ItemHolder holder, ShoppingItem item) {
        holder.title.setText(item.name);
        int flags = holder.title.getPaintFlags();
        holder.title.setPaintFlags(item.checked
                ? flags | Paint.STRIKE_THRU_TEXT_FLAG
                : flags & ~Paint.STRIKE_THRU_TEXT_FLAG);
        holder.subtitle.setText(subtitle(item));
        holder.auto.setVisibility(item.autoGenerated ? View.VISIBLE : View.GONE);

        // detach the listener before changing the state, or recycled rows fire false events
        holder.check.setOnCheckedChangeListener(null);
        holder.check.setChecked(item.checked);
        holder.check.setOnCheckedChangeListener(
                (button, isChecked) -> listener.onCheckedChanged(item, isChecked));

        holder.itemView.setOnClickListener(v -> listener.onItemClicked(item));
    }

    /** @return "2 pcs · Walmart", leaving out what is empty */
    private static String subtitle(ShoppingItem item) {
        StringBuilder text = new StringBuilder(ShoppingListFormatter.formatQuantity(item.quantity));
        if (!item.unit.isEmpty()) {
            text.append(' ').append(item.unit);
        }
        if (item.store != null && !item.store.isEmpty()) {
            text.append(" · ").append(item.store);
        }
        return text.toString();
    }

    /** views of a shop header */
    static class HeaderHolder extends RecyclerView.ViewHolder {
        final TextView name;
        final TextView count;
        final View map;

        HeaderHolder(@NonNull View itemView) {
            super(itemView);
            name = itemView.findViewById(R.id.txtStoreName);
            count = itemView.findViewById(R.id.txtStoreCount);
            map = itemView.findViewById(R.id.btnStoreMap);
        }
    }

    /** views of one item row */
    static class ItemHolder extends RecyclerView.ViewHolder {
        final CheckBox check;
        final TextView title;
        final TextView subtitle;
        final TextView auto;

        ItemHolder(@NonNull View itemView) {
            super(itemView);
            check = itemView.findViewById(R.id.chk);
            title = itemView.findViewById(R.id.txtTitle);
            subtitle = itemView.findViewById(R.id.txtSubtitle);
            auto = itemView.findViewById(R.id.txtAuto);
        }
    }
}
