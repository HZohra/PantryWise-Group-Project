package com.cp470.groupproject.ui.shoppinglist;

import android.graphics.Paint;
import android.view.LayoutInflater;
import android.view.View;
import android.view.ViewGroup;
import android.widget.CheckBox;
import android.widget.TextView;

import androidx.annotation.NonNull;
import androidx.recyclerview.widget.DiffUtil;
import androidx.recyclerview.widget.ListAdapter;
import androidx.recyclerview.widget.RecyclerView;

import com.cp470.groupproject.R;
import com.cp470.groupproject.data.entity.ShoppingItem;
import com.cp470.groupproject.util.ShoppingListFormatter;

import java.util.Objects;

/** Adapter of the shopping list: one row per item with a checkbox, name and details. */
public class ShoppingListAdapter extends ListAdapter<ShoppingItem, ShoppingListAdapter.Holder> {

    /** events of the rows, handled by the activity */
    public interface Listener {
        /** the checkbox of a row was ticked or unticked by the user */
        void onCheckedChanged(ShoppingItem item, boolean checked);

        /** a row was tapped (to edit it) */
        void onItemClicked(ShoppingItem item);
    }

    private static final DiffUtil.ItemCallback<ShoppingItem> DIFF =
            new DiffUtil.ItemCallback<ShoppingItem>() {
                @Override
                public boolean areItemsTheSame(@NonNull ShoppingItem a, @NonNull ShoppingItem b) {
                    return a.id == b.id;
                }

                // ShoppingItem has no equals(), so compare the shown fields one by one
                @Override
                public boolean areContentsTheSame(@NonNull ShoppingItem a, @NonNull ShoppingItem b) {
                    return a.name.equals(b.name)
                            && a.quantity == b.quantity
                            && a.unit.equals(b.unit)
                            && Objects.equals(a.store, b.store)
                            && a.checked == b.checked
                            && a.autoGenerated == b.autoGenerated;
                }
            };

    private final Listener listener;

    /** @param listener receives the clicks of the rows */
    public ShoppingListAdapter(@NonNull Listener listener) {
        super(DIFF);
        this.listener = listener;
    }

    @NonNull
    @Override
    public Holder onCreateViewHolder(@NonNull ViewGroup parent, int viewType) {
        View view = LayoutInflater.from(parent.getContext())
                .inflate(R.layout.item_shopping, parent, false);
        return new Holder(view);
    }

    @Override
    public void onBindViewHolder(@NonNull Holder holder, int position) {
        ShoppingItem item = getItem(position);

        holder.title.setText(item.name);
        int flags = holder.title.getPaintFlags();
        holder.title.setPaintFlags(item.checked
                ? flags | Paint.STRIKE_THRU_TEXT_FLAG
                : flags & ~Paint.STRIKE_THRU_TEXT_FLAG);
        holder.subtitle.setText(subtitle(item));
        holder.auto.setVisibility(item.autoGenerated ? View.VISIBLE : View.GONE);

        // detach the listener before changing the state, or recycled rows fire false events
        holder.check.setOnCheckedChangeListener(null);
        holder.check.setChecked(item.checked);
        holder.check.setOnCheckedChangeListener(
                (button, isChecked) -> listener.onCheckedChanged(item, isChecked));

        holder.itemView.setOnClickListener(v -> listener.onItemClicked(item));
    }

    /** @return "2 pcs · Walmart", leaving out what is empty */
    private static String subtitle(ShoppingItem item) {
        StringBuilder text = new StringBuilder(ShoppingListFormatter.formatQuantity(item.quantity));
        if (!item.unit.isEmpty()) {
            text.append(' ').append(item.unit);
        }
        if (item.store != null && !item.store.isEmpty()) {
            text.append(" · ").append(item.store);
        }
        return text.toString();
    }

    /** views of one row */
    static class Holder extends RecyclerView.ViewHolder {
        final CheckBox check;
        final TextView title;
        final TextView subtitle;
        final TextView auto;

        Holder(@NonNull View itemView) {
            super(itemView);
            check = itemView.findViewById(R.id.chk);
            title = itemView.findViewById(R.id.txtTitle);
            subtitle = itemView.findViewById(R.id.txtSubtitle);
            auto = itemView.findViewById(R.id.txtAuto);
        }
    }
}
