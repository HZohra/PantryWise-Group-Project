package com.cp470.groupproject.shopping;

import androidx.annotation.NonNull;
import androidx.annotation.Nullable;

import com.cp470.groupproject.data.entity.MealPlan;
import com.cp470.groupproject.data.entity.ShoppingItem;
import com.cp470.groupproject.data.model.StockSummary;
import com.cp470.groupproject.data.repository.PantryRepository;
import com.cp470.groupproject.util.ShoppingCalculator;

import java.util.List;

/**
 * Fills the shopping list from the meal plan: reads plans, stock and list, lets
 * {@link ShoppingCalculator} work out what is missing, and saves the result.
 */
public class ShoppingListGenerator {

    /** what a generation did: how many meals it looked at and how many items it added */
    public static final class Result {
        /** meals in the period that are not cooked yet (the ones that count) */
        public final int meals;
        /** items added to the shopping list */
        public final int added;

        Result(int meals, int added) {
            this.meals = meals;
            this.added = added;
        }
    }

    private final PantryRepository repository;

    /** @param repository where plans, stock and the list are read and the result is saved */
    public ShoppingListGenerator(@NonNull PantryRepository repository) {
        this.repository = repository;
    }

    /**
     * generates the missing items for the meals planned in a period. background thread only.
     *
     * @param from start of the period, in milliseconds
     * @param to end of the period (included), in milliseconds
     * @param callback receives the result (background thread), may be null. with no pending meals
     *                 in the period the result has {@code meals == 0}, which is not the same as
     *                 having everything in stock
     */
    public void generate(long from, long to,
                         @Nullable PantryRepository.ResultCallback<Result> callback) {
        List<MealPlan> plans = repository.getMealPlansSync(from, to);
        List<StockSummary> stock = repository.getStockSummarySync();
        List<ShoppingItem> list = repository.getShoppingItemsSync();
        List<ShoppingItem> missing = ShoppingCalculator.computeMissing(plans, stock, list);
        int meals = 0;
        for (MealPlan plan : plans) {
            if (!plan.completed) meals++;
        }
        final int pendingMeals = meals;
        repository.replaceAutoGeneratedShoppingItems(missing, callback == null ? null
                : added -> callback.onResult(new Result(pendingMeals, added)));
    }
}
